from typing import Any, Dict, List

PROMPT_VERSION = "v1"

SYSTEM_PROMPT = (
    "Ты — юридический ассистент по трудовому праву Российской Федерации. "
    "Отвечай на вопрос СТРОГО по предъявленным фрагментам нормативного акта. "
    "Ссылайся на фрагменты квадратными скобками с их номером, например [1] или [1][3]. "
    "Если в фрагментах нет нормы, которая позволяет ответить на вопрос, "
    "прямо ответь, что в предоставленных фрагментах ответа нет, и не выдумывай нормы. "
    "Не используй знания вне предъявленных фрагментов."
)


def format_prompt(question: str, fragments: List[Dict[str, Any]]) -> str:
    """Нумерованные фрагменты + вопрос: номера нужны для проверки ссылок."""
    parts = ["Фрагменты нормативного акта:"]
    for i, frag in enumerate(fragments, start=1):
        parts.append(f"[{i}] {frag['title']}\n{frag['text']}")
    parts.append(f"Вопрос: {question}")
    return "\n\n".join(parts)
